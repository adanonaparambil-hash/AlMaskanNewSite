// Builds the site as plain files for cPanel hosting (e.g. GoDaddy Web Hosting) and zips it:
//   node scripts/build-cpanel.mjs            → deploy/AlMaskanVillage-cPanel.zip
// The Node-only parts (API routes, the language proxy) are set aside during the build and restored afterwards;
// on cPanel their jobs are done by PHP (deploy/cpanel/api) and by the generated .htaccess.
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import sharp from 'sharp';
import { REDIRECTS } from '../redirects.mjs';
// Node 22.18+ reads this TypeScript file directly (types are stripped)
import { IMG_WIDTHS } from '../src/lib/image-loader.ts';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'out');
const HOLD = path.join(ROOT, '.cpanel-hold');
const ZIP = path.join(ROOT, 'deploy', 'AlMaskanVillage-cPanel.zip');
// Windows' own bsdtar writes real .zip files (Git Bash's tar would read "E:" as a remote host)
const TAR = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe');
const ASIDE = ['src/app/api', 'src/proxy.ts'];

// ---------------------------------------------------------------- build with the Node-only parts set aside
// (--package-only re-packages an existing out/ without rebuilding)
if (!process.argv.includes('--package-only')) {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.rmSync(path.join(ROOT, '.next'), { recursive: true, force: true });
  fs.mkdirSync(HOLD, { recursive: true });
  for (const p of ASIDE) if (fs.existsSync(path.join(ROOT, p))) fs.renameSync(path.join(ROOT, p), path.join(HOLD, path.basename(p)));
  try {
    execSync('npx next build', {
      stdio: 'inherit',
      env: { ...process.env, STATIC_EXPORT: '1', NEXT_PUBLIC_HOSTING: 'cpanel', BUILD_CPUS: process.env.BUILD_CPUS || '3', NODE_OPTIONS: '--max-old-space-size=4096' },
    });
  } finally {
    for (const p of ASIDE) {
      const held = path.join(HOLD, path.basename(p));
      if (fs.existsSync(held)) fs.renameSync(held, path.join(ROOT, p));
    }
    fs.rmSync(HOLD, { recursive: true, force: true });
    // the next Vercel/Node build must not reuse this export's cache
    fs.rmSync(path.join(ROOT, '.next'), { recursive: true, force: true });
  }
}

// ---------------------------------------------------------------- sized images (there is no image optimiser on cPanel)
// every raster under /assets in each width the image loader asks for, as WebP: phones get small files
{
  const widths = IMG_WIDTHS;
  const files = [];
  (function walk(d) {
    for (const f of fs.readdirSync(d)) {
      const p = path.join(d, f);
      if (fs.statSync(p).isDirectory()) walk(p);
      else if (/\.(jpe?g|png|webp)$/i.test(f)) files.push(p);
    }
  })(path.join(OUT, 'assets'));
  let bytes = 0;
  for (const file of files) {
    const rel = path.relative(OUT, file).replace(/\.(jpe?g|png|webp)$/i, '.webp');
    await Promise.all(widths.map(async (w) => {
      const dest = path.join(OUT, '_img', String(w), rel);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      const info = await sharp(file).rotate().resize({ width: w, withoutEnlargement: true }).webp({ quality: 74 }).toFile(dest);
      bytes += info.size;
    }));
  }
  console.log(`sized images: ${files.length} images × ${widths.length} widths (${(bytes / 1048576).toFixed(1)} MB)`);
}

// ---------------------------------------------------------------- PHP endpoints and the install notes
fs.cpSync(path.join(ROOT, 'deploy/cpanel'), OUT, { recursive: true });

// ---------------------------------------------------------------- .htaccess: clean URLs, languages, redirects
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const redirectRules = REDIRECTS.map(
  (r) => `RewriteRule ^${esc(r.source.slice(1))}/?$ ${r.destination} [R=${r.permanent ? 301 : 302},L]`,
).join('\n');

const htaccess = `# Al Maskaan Village — generated by scripts/build-cpanel.mjs. Do not edit by hand; rebuild instead.
Options -MultiViews -Indexes
DirectorySlash Off
DirectoryIndex index.html
AddDefaultCharset UTF-8
ErrorDocument 404 /404.html

# the install notes stay on the server but are not served
<Files "README-INSTALL.txt">
  Require all denied
</Files>

<IfModule mod_rewrite.c>
RewriteEngine On

# force HTTPS
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !=https
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]

# the PHP endpoints behind the inquiry form, the visitor counter and the site assistant
RewriteRule ^api/(inquiry|visits|chat)/?$ api/$1.php [L]

# old and moved pages → their new address, in one hop
${redirectRules}

# /en/… is never a public address: English pages live at the unprefixed URL
RewriteCond %{THE_REQUEST} \\s/en(/[^\\s?]*)?[\\s?]
RewriteRule ^en/?(.*)$ /$1 [R=301,L]

# a trailing slash on a page address → the address without it (pages are files, never folders)
RewriteCond %{REQUEST_URI} !^/(explorer|_next|_img|assets|api)/
RewriteRule ^(.+)/$ /$1 [R=301,L]

# page-data files for instant navigation: the browser asks for __next.a.b.txt, the export stores __next.a/b.txt
# (one dot becomes a slash per pass; Apache re-runs the rules after each internal rewrite)
RewriteRule ^(.*__next\\.[^/.]+(?:/[^/.]+)*)\\.([^/]*\\.txt)$ $1/$2 [L]

# Arabic pages: /ar → ar.html, /ar/rooms → ar/rooms.html
RewriteRule ^ar$ ar.html [L]
RewriteCond %{DOCUMENT_ROOT}/$1.html -f
RewriteRule ^(ar/.+)$ $1.html [L]

# English pages are stored under /en: / → en.html, /rooms → en/rooms.html, and their data files
RewriteRule ^$ en.html [L]
RewriteCond %{REQUEST_URI} !^/(ar|en|_next|_img|assets|api|explorer)(/|$)
RewriteCond %{DOCUMENT_ROOT}/en/$1.html -f
RewriteRule ^(.+)$ en/$1.html [L]
RewriteCond %{REQUEST_URI} !^/(ar|en|_next|_img|assets|api|explorer)(/|$)
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{DOCUMENT_ROOT}/en/$1 -f
RewriteRule ^(.+)$ en/$1 [L]
</IfModule>

# long caching for files whose names change with every build, short for pages
<IfModule mod_headers.c>
  <FilesMatch "\\.(js|css|woff2?)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(jpe?g|png|webp|avif|svg|mp4|ico)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
  <FilesMatch "\\.(html|txt)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/plain text/css application/javascript application/json image/svg+xml
</IfModule>
`;
fs.writeFileSync(path.join(OUT, '.htaccess'), htaccess);

// ---------------------------------------------------------------- zip
fs.mkdirSync(path.dirname(ZIP), { recursive: true });
fs.rmSync(ZIP, { force: true });
if (process.platform === 'win32') {
  // keeps dot-files such as .htaccess
  // listing the entries (rather than ".") keeps paths clean: "index.html", not "./index.html"
  const entries = fs.readdirSync(OUT).map((e) => `"${e}"`).join(' ');
  execSync(`"${TAR}" -a -c -f "${ZIP}" -C "${OUT}" ${entries}`, { stdio: 'inherit' });
} else {
  execSync(`cd "${OUT}" && zip -qr "${ZIP}" .`, { stdio: 'inherit', shell: '/bin/sh' });
}
const files = execSync(process.platform === 'win32' ? `"${TAR}" -t -f "${ZIP}"` : `unzip -Z1 "${ZIP}"`).toString().trim().split('\n').length;
console.log(`\n${path.relative(ROOT, ZIP)} — ${(fs.statSync(ZIP).size / 1048576).toFixed(1)} MB, ${files} entries`);
