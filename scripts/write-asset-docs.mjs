// Generates docs/asset-inventory.md and source-assets/manifest.json from the download + curation manifests.
import fs from 'node:fs';
import sharp from 'sharp';

const raw = JSON.parse(fs.readFileSync('source-assets/data/download-manifest.json', 'utf8'));
const cur = JSON.parse(fs.readFileSync('source-assets/curated-manifest.json', 'utf8'));
const used = new Map();
for (const c of cur) used.set(c.original, [...(used.get(c.original) ?? []), c.local]);

const rows = [];
for (const r of raw) {
  const p = `source-assets/originals/${r.file}`;
  let w = r.w, h = r.h;
  if (fs.existsSync(p) && /\.(jpe?g|png|webp)$/i.test(p)) {
    try { const m = await sharp(p).metadata(); w = m.width; h = m.height; } catch { /* keep */ }
  }
  const type = r.file.split('.').pop().toLowerCase();
  const section = /Dr|Mr\.-|people/i.test(r.file) ? 'People' : /logo|Logo|favicon|haven-of-5|AMV-/.test(r.file) ? 'Logos / brand' : /2025_09/.test(r.file) ? 'Clients' : /WhatsApp|^2024_02_\d|-min\./.test(r.file) ? 'Gallery / renders' : /AlMaskaanVillage_|Al-Maskaan-Village-|Silal|ATM|Joyalukkas/.test(r.file) ? 'News' : 'Other';
  rows.push({ source: r.source, file: r.file, type, w, h, bytes: r.bytes, status: r.status, section, used: used.get(r.file) ?? [] });
}
fs.writeFileSync('source-assets/manifest.json', JSON.stringify(rows, null, 1));

const usedCount = rows.filter((r) => r.used.length).length;
let md = `# Asset inventory

Generated by \`scripts/write-asset-docs.mjs\` from the actual downloads. All originals are kept untouched in \`source-assets/originals/\` (flattened names: \`<year>_<month>_<filename>\`); the full machine-readable record (source URL, dimensions, bytes, status, where used) is \`source-assets/manifest.json\`.

## Summary

| | |
|---|---|
| Files requested | ${rows.length} |
| Downloaded OK | ${rows.filter((r) => r.status.startsWith('ok')).length} |
| Failed | ${rows.filter((r) => !r.status.startsWith('ok')).length} |
| Opened & verified readable (sharp) | ${rows.filter((r) => r.w).length} raster images (SVGs/unreadable: ${rows.filter((r) => !r.w).length}) |
| Total size of originals | ${(rows.reduce((a, b) => a + b.bytes, 0) / 1e6).toFixed(1)} MB |
| Originals used in the redesign | ${usedCount} (optimised copies in \`public/assets/\`) |

Source: the site's public WordPress REST media library (\`/wp-json/wp/v2/media\`, 292 items listed of 344 reported) plus every image URL found in rendered page HTML/CSS. No authentication or download protection was bypassed.

## Not downloaded / not reusable

- **Hero video** — the homepage film is a YouTube embed (\`https://www.youtube.com/watch?v=ngpgxRNUFh4\`). It is not downloadable from the site and was *not* ripped from YouTube; the new site embeds it with a click-to-load player.
- **Homepage hero slider slides** — the slider's image slides are not exposed in page markup or CSS; the redesigned hero uses the village aerial rendering (\`2024/03/Al-Maskaan-Village.jpg\`) instead.
- **Holding / sister company logos** — rendered by JavaScript carousels on the original footer; no image URLs were exposed. Missing.
- **Media-library items not listed by the API** — about 52 of 344 reported items were not returned by the public API (likely private/attached). Not collected.
- **Very small / thumbnail-only files** (gallery thumbnails ≤ 475 px, \`-min\` variants, 286×392 menu tiles) were downloaded but not used; the 1600 px gallery originals are used instead.
- **Icons** — the original purpose/vision/mission icons are 93 px PNGs; the redesign uses typography instead.

## Rights and usage notes

- Everything was published by Al Maskaan Village on its own website, but **public accessibility is not a licence**. Confirm with the owner that the redesigned site may republish them.
- Many images are **architectural renderings**; some office/lobby renders show a third-party brand sign (“Regus”) — those were deliberately excluded.
- Catering food shots (canapés, desserts, chef plating) and some news art (ATM, bank, charts, Trufud/market photos) look like **stock photography** used on the original site; licences unknown. Used only for catering/news where the original site used them — see the remaining-limitations list in docs/testing-report.md.
- **Client logos** and partner photos (Al-Nab'a, Home Suite, Muscat Hills, Food Development Co., KV Group, Suhol Alfayha, Bank Muscat, Joyalukkas, etc.) are third-party trademarks.
- Portraits of the leadership team are used as on the original About page.

## Curated set used by the site

| Key | Original | Local file | Size |
|---|---|---|---|
`;
for (const c of cur.filter((c) => !c.key.startsWith('news.') && !c.key.startsWith('gallery.'))) {
  md += `| ${c.key} | ${c.original} | \`public/${c.local}\` | ${c.w}×${c.h} |\n`;
}
md += `\n### Gallery (${cur.filter((c) => c.key.startsWith('gallery.')).length}) and news images (${cur.filter((c) => c.key.startsWith('news.')).length})\n\nSee \`source-assets/curated-manifest.json\`; gallery files are in \`public/assets/images/gallery/\`, news images in \`public/assets/images/news/\` (named \`<date>-<article-slug>.jpg\`).\n\n## Full download list by section\n\n`;
for (const s of [...new Set(rows.map((r) => r.section))]) {
  const rs = rows.filter((r) => r.section === s);
  md += `### ${s} (${rs.length})\n\n| Source URL | Local original | Type | Dimensions | Status | Used as |\n|---|---|---|---|---|---|\n`;
  for (const r of rs) md += `| ${r.source.replace('https://almaskaanvillage.com/wp-content/uploads/', '…/')} | ${r.file} | ${r.type} | ${r.w ? r.w + '×' + r.h : '—'} | ${r.status} | ${r.used.map((u) => u.replace('assets/images/', '')).join(', ') || 'not used'} |\n`;
  md += '\n';
}
fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/asset-inventory.md', md);
console.log('written', rows.length, 'rows;', usedCount, 'used');
